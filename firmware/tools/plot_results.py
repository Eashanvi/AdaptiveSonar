#!/usr/bin/env python3
"""
plot_results.py - turn the host simulator's CSVs into the figures you put on
a slide.  Deliberately mirrors the MATLAB figure set (waveform, instantaneous
frequency, spectrum, spectrogram) so the two can be shown side by side.

    make plots          # builds, runs, plots
    python3 Tools/plot_results.py
"""
import csv, os, sys, math
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

OUT = "out"
FIG = "figures"
os.makedirs(FIG, exist_ok=True)

INK   = "#0f2b3d"
ACC   = "#1b7f9e"
ACC2  = "#c2521f"
GRID  = "#d8e2e8"

plt.rcParams.update({
    "font.family": "DejaVu Sans", "font.size": 9,
    "axes.edgecolor": INK, "axes.labelcolor": INK, "text.color": INK,
    "xtick.color": INK, "ytick.color": INK,
    "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6,
    "figure.facecolor": "white", "axes.facecolor": "white",
})

def read(path):
    if not os.path.exists(path):
        return None
    with open(path) as f:
        r = list(csv.DictReader(f))
    if not r:
        return None
    keys = r[0].keys()
    return {k: np.array([float(row[k]) for row in r]) for k in keys}

def stem(name):
    return os.path.join(OUT, name)

def panel(name, title):
    w = read(stem(name + "_wave.csv"))
    s = read(stem(name + "_spec.csv"))
    if w is None:
        return
    fig, ax = plt.subplots(1, 3, figsize=(13, 3.1))

    ax[0].plot(w["t_us"] / 1000.0, w["amplitude"], color=ACC, lw=0.5)
    ax[0].set_xlabel("time (ms)"); ax[0].set_ylabel("normalised amplitude")
    ax[0].set_title("transmitted pulse", loc="left")

    if np.any(w["inst_freq_hz"] > 0):
        ax[1].plot(w["t_us"] / 1000.0, w["inst_freq_hz"] / 1000.0,
                   color=ACC2, lw=1.4)
    ax[1].set_xlabel("time (ms)"); ax[1].set_ylabel("f (kHz, DAC scale)")
    ax[1].set_title("instantaneous frequency", loc="left")

    if s is not None:
        m = s["magnitude"]; m = m / (m.max() if m.max() > 0 else 1)
        db = 20 * np.log10(np.maximum(m, 1e-6))
        ax[2].plot(s["freq_hz"] / 1000.0, db, color=ACC, lw=0.8)
        ax[2].set_ylim(-90, 5)
    ax[2].set_xlabel("frequency (kHz, DAC scale)"); ax[2].set_ylabel("dB")
    ax[2].set_title("spectrum", loc="left")

    fig.suptitle(title, x=0.008, ha="left", fontsize=11, weight="bold")
    fig.tight_layout(rect=[0, 0, 1, 0.92])
    p = os.path.join(FIG, name + ".png")
    fig.savefig(p, dpi=150); plt.close(fig)
    print("  " + p)

def spectrogram(name, title):
    w = read(stem(name + "_wave.csv"))
    if w is None: return
    x = w["amplitude"]
    dt = (w["t_us"][1] - w["t_us"][0]) * 1e-6
    fs = 1.0 / dt
    if len(x) < 512: return
    fig, ax = plt.subplots(figsize=(5.2, 3.2))
    ax.specgram(x, NFFT=256, Fs=fs / 1000.0, noverlap=192,
                cmap="viridis", scale="dB")
    ax.set_xlabel("time (s x1000)"); ax.set_ylabel("frequency (kHz)")
    ax.set_title(title, loc="left", fontsize=10, weight="bold")
    ax.grid(False)
    fig.tight_layout()
    p = os.path.join(FIG, name + "_spectrogram.png")
    fig.savefig(p, dpi=150); plt.close(fig)
    print("  " + p)

def waveform_gallery():
    names = ["LFM", "GEOMETRIC", "HYPERBOLIC", "BARKER13", "STEPPED", "CW"]
    fig, axes = plt.subplots(2, 3, figsize=(13, 5.4))
    for ax, n in zip(axes.ravel(), names):
        w = read(stem("wf_" + n + "_wave.csv"))
        if w is None: continue
        ax.plot(w["t_us"] / 1000.0, w["amplitude"], color=ACC, lw=0.45)
        if np.any(w["inst_freq_hz"] > 0):
            a2 = ax.twinx()
            a2.plot(w["t_us"] / 1000.0, w["inst_freq_hz"] / 1000.0,
                    color=ACC2, lw=1.3)
            a2.set_ylabel("kHz", color=ACC2, fontsize=8)
            a2.tick_params(colors=ACC2, labelsize=7); a2.grid(False)
        ax.set_title(n, loc="left", weight="bold", fontsize=10)
        ax.set_xlabel("ms", fontsize=8)
    fig.suptitle("all six waveform types, same band and duration, "
                 "generated by the same firmware",
                 x=0.008, ha="left", fontsize=11, weight="bold")
    fig.tight_layout(rect=[0, 0, 1, 0.94])
    p = os.path.join(FIG, "waveform_gallery.png")
    fig.savefig(p, dpi=150); plt.close(fig)
    print("  " + p)

def window_gallery():
    names = ["RECT", "HAMMING", "HANN", "BLACKMAN", "TUKEY"]
    fig, ax = plt.subplots(1, 2, figsize=(12, 3.6))
    cols = plt.cm.viridis(np.linspace(0.05, 0.85, len(names)))
    for c, n in zip(cols, names):
        w = read(stem("win_" + n + "_wave.csv"))
        s = read(stem("win_" + n + "_spec.csv"))
        if w is not None:
            ax[0].plot(w["t_us"] / 1000.0, w["amplitude"], color=c, lw=0.5,
                       label=n, alpha=0.9)
        if s is not None:
            m = s["magnitude"]; m = m / (m.max() if m.max() > 0 else 1)
            ax[1].plot(s["freq_hz"] / 1000.0,
                       20 * np.log10(np.maximum(m, 1e-7)), color=c, lw=0.9,
                       label=n)
    ax[0].set_title("envelope: what the amplifier sees", loc="left",
                    weight="bold", fontsize=10)
    ax[0].set_xlabel("ms"); ax[0].legend(fontsize=7, frameon=False)
    ax[1].set_title("spectrum: what the sidelobes cost", loc="left",
                    weight="bold", fontsize=10)
    ax[1].set_xlabel("kHz"); ax[1].set_ylabel("dB"); ax[1].set_ylim(-100, 5)
    ax[1].legend(fontsize=7, frameon=False)
    fig.tight_layout()
    p = os.path.join(FIG, "window_comparison.png")
    fig.savefig(p, dpi=150); plt.close(fig)
    print("  " + p)

def decisions_table():
    if not os.path.exists(stem("decisions.csv")): return
    with open(stem("decisions.csv")) as f:
        rows = list(csv.DictReader(f))
    fig, ax = plt.subplots(2, 2, figsize=(11, 6))
    names = [r["scenario"] for r in rows]
    xs = np.arange(len(rows))

    def bar(a, key, label, scale=1.0, col=ACC):
        v = np.array([float(r[key]) for r in rows]) * scale
        a.bar(xs, v, color=col, width=0.62)
        a.set_xticks(xs)
        a.set_xticklabels([n.replace("_", "\n") for n in names], fontsize=7)
        a.set_title(label, loc="left", weight="bold", fontsize=10)
        for x, y in zip(xs, v):
            a.text(x, y, ("%.3g" % y), ha="center", va="bottom", fontsize=7)

    bar(ax[0][0], "bandwidth_hz", "bandwidth (kHz)", 1e-3)
    bar(ax[0][1], "pulse_ms", "pulse duration (ms)", 1.0, ACC2)
    bar(ax[1][0], "range_res_m", "range resolution (m)", 1.0, ACC)
    bar(ax[1][1], "avg_power_mw", "average power (mW)", 1.0, ACC2)
    fig.suptitle("the same firmware, five environments: "
                 "what the adaptation engine decided",
                 x=0.008, ha="left", fontsize=11, weight="bold")
    fig.tight_layout(rect=[0, 0, 1, 0.94])
    p = os.path.join(FIG, "adaptation_decisions.png")
    fig.savefig(p, dpi=150); plt.close(fig)
    print("  " + p)

if __name__ == "__main__":
    if not os.path.isdir(OUT):
        print("run ./build/host_sim first"); sys.exit(1)
    print("writing figures/")
    for n, t in [("clear_shallow_reef", "clear shallow reef  -  BARKER-13, resolution priority"),
                 ("coastal_medium",     "coastal, medium turbidity  -  LFM chirp"),
                 ("muddy_estuary_deep", "deep muddy estuary  -  geometric sweep, penetration priority"),
                 ("transit_leg",        "transit  -  stepped burst, minimum energy"),
                 ("battery_critical",   "battery critical  -  near-CW, power save")]:
        panel(n, t)
    spectrogram("muddy_estuary_deep", "spectrogram: geometric sweep")
    spectrogram("coastal_medium", "spectrogram: LFM chirp")
    waveform_gallery()
    window_gallery()
    decisions_table()
    print("done")
